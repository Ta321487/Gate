def resolve_ai_knowledge_skin(
    domain: str = "",
    title: str = "",
    proposal_text: str = "",
) -> str:
    """选定 FAQ 种子皮：优先域自有皮 / 货皮，尽量不落 generic。"""
    from app.bake.scene_scan import (
        activity_product_kind,
        event_product_kind,
        food_product_kind,
        library_product_kind,
        procure_product_kind,
        recruit_product_kind,
        scene_lost_parts,
        shop_catalog_kind,
    )

    text = f"{title or ''}\n{proposal_text or ''}"
    dom = (domain or "").strip().upper()

    def _shop_skin() -> str:
        return f"shop_{shop_catalog_kind(title, proposal_text)}"

    def _library_skin() -> str:
        pk = library_product_kind(title, proposal_text)
        if pk == "archive":
            return "library_archive"
        if pk == "drift":
            return "library_drift"
        return "library_book"

    def _food_skin() -> str:
        if food_product_kind(title, proposal_text) == "canteen":
            return "food_canteen"
        return "food"

    def _activity_skin() -> str:
        ak = activity_product_kind(title, proposal_text)
        if ak == "blood":
            return "activity_blood"
        if ak == "ticket":
            return "activity_ticket"
        if ak == "camp":
            return "activity_camp"
        if ak == "cert":
            if any(x in (title or "") for x in ("防暴恐", "反恐", "安全培训")):
                return "activity_security"
            return "activity_cert"
        return "activity"

    def _event_skin() -> str:
        if event_product_kind(title, proposal_text) == "household":
            return "event_household"
        return "event"

    def _lost_skin() -> str:
        sc = scene_lost_parts(title, proposal_text)
        if sc == "baggage":
            return "lost_baggage"
        if sc == "adopt":
            return "lost_adopt"
        if sc == "donate":
            return "lost_donate"
        return "lost"

    def _procure_skin() -> str:
        if procure_product_kind(title, proposal_text) == "journal":
            return "procure_journal"
        return "procure"

    def _recruit_skin() -> str:
        if recruit_product_kind(title, proposal_text) == "witkey":
            return "recruit_witkey"
        return "recruit"

    # 具名域 → 自有皮（商城/图书/点餐另算货皮；活动/事件/失物/采购/招聘按深皮细分）
    domain_skin: dict[str, str] = {
        "DOM-DORM": "dorm",
        "DOM-PROPERTY": "property",
        "DOM-IT": "it",
        "DOM-FITOUT": "fitout",
        "DOM-ATTEND": "attend",
        "DOM-DOCLIB": "doclib",
        "DOM-HOTEL": "hotel",
        "DOM-TOUR": "tour",
        "DOM-CARRENT": "carrent",
        "DOM-LISTING": "listing",
        "DOM-CINEMA": "cinema",
        "DOM-HOSPITAL": "hospital",
        "DOM-SALON": "salon",
        "DOM-MEETING": "meeting",
        "DOM-PARKING": "parking",
        "DOM-EQUIP": "equip",
        "DOM-CRM": "crm",
        "DOM-PARCEL": "parcel",
        "DOM-MEDIA": "media",
        "DOM-MUSIC": "music",
        "DOM-BLOG": "blog",
        "DOM-FORUM": "forum",
        "DOM-BED": "bed",
        "DOM-EVENT": "__event__",
        "DOM-ACTIVITY": "__activity__",
        "DOM-LOST": "__lost__",
        "DOM-PROCURE": "__procure__",
        "DOM-RECRUIT": "__recruit__",
    }

    if dom == "DOM-SHOP":
        return _shop_skin()
    if dom == "DOM-LIBRARY":
        return _library_skin()
    if dom == "DOM-FOOD":
        return _food_skin()
    if dom in domain_skin:
        key = domain_skin[dom]
        if key == "__event__":
            return _event_skin()
        if key == "__activity__":
            return _activity_skin()
        if key == "__lost__":
            return _lost_skin()
        if key == "__procure__":
            return _procure_skin()
        if key == "__recruit__":
            return _recruit_skin()
        return key

    # 无明确域：按开题词选皮（细优先于粗）
    if re.search(r"宿舍报修|宿管|寝室|水电故障", text) or (
        re.search(r"宿舍", text) and re.search(r"报修", text)
    ):
        return "dorm"
    if re.search(r"物业报修|物业工单|小区物业", text):
        return "property"
    if re.search(r"校园网|机房|终端故障|IT报修|网络报修", text):
        return "it"
    if re.search(r"装修备案|室内装修|外立面", text):
        return "fitout"
    if re.search(r"请假|销假|考勤", text):
        return "attend"
    if re.search(r"食堂|档口", text):
        return "food_canteen"
    if re.search(r"点餐|外卖|餐厅|奶茶", text):
        return "food"
    if re.search(r"文库|资料下载|制度文件|课件下载", text):
        return "doclib"
    if re.search(r"图书|借阅|馆员|阅读助手|图书馆|档案卷宗|漂流", text):
        return _library_skin()
    if re.search(r"客房|酒店|宾馆|民宿|入住|离店", text):
        return "hotel"
    if re.search(r"旅行社|跟团|线路报名|出团|研学线路", text):
        return "tour"
    if re.search(r"租车|取还车|车型租期|汽车租赁", text):
        return "carrent"
    if re.search(r"房源|带看|整租|合租|二手房", text):
        return "listing"
    if re.search(r"影院|选座|场次|IMAX|巨幕", text):
        return "cinema"
    if re.search(r"挂号|门诊|医院预约|号源", text):
        return "hospital"
    if re.search(r"美发|理发|美甲|预约造型", text):
        return "salon"
    if re.search(r"会议室|场地预约", text):
        return "meeting"
    if re.search(r"车位预约|停车预约|充电桩车位", text):
        return "parking"
    if re.search(r"防返贫|帮扶户|监测户", text):
        return "event_household"
    if re.search(r"事件上报|晨午检|随访|巡检打卡|走访打卡", text):
        return "event"
    if re.search(r"行李挂失|航班行李|行李认领", text):
        return "lost_baggage"
    if re.search(r"宠物领养|流浪动物|领养申请", text):
        return "lost_adopt"
    if re.search(r"捐赠物资|物资认领|捐赠认领", text):
        return "lost_donate"
