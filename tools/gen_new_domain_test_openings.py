def _targets_by_list_id() -> dict[str, list[Path]]:
    found: dict[str, list[Path]] = {}
    for p in SAMPLES.rglob("*.txt"):
        if "_generated" in p.parts or "upload_cluster" in str(p):
            continue
        m = re.match(r"([PC])-(\d+)-", p.name)
        if not m:
            continue
        key = f"{m.group(1)}-{int(m.group(2)):02d}"
        found.setdefault(key, []).append(p)
    return found


def _pick_target(list_id: str, domain: str, title_core: str, pool: dict[str, list[Path]]) -> Path:
    lid = f"{list_id[0]}-{int(list_id[2:]):02d}"
    cands = [c for c in pool.get(lid, []) if domain in c.name]
    if not cands:
        cands = pool.get(lid, [])
    for c in cands:
        if title_core[:6] in c.name or (
            "高校在线考试" in title_core and "高校在线考试" in c.name
        ):
            return c
    if len(cands) == 1:
        return cands[0]
    for c in cands:
        if domain in c.name:
            return c
    raise FileNotFoundError(f"no sample file for {list_id} {domain} {title_core}")


def main() -> None:
    pool = _targets_by_list_id()
    written: list[str] = []
    for spec in SPECS:
        seq, domain, list_id, title_core, *_ = spec
        dest = _pick_target(list_id, domain, title_core, pool)
        dest.write_text(render(spec), encoding="utf-8")
        written.append(f"{seq} {list_id} -> {dest.relative_to(SAMPLES).as_posix()}")
    for line in written:
        print(line)
    print(f"wrote {len(written)} openings into P/C presets under {SAMPLES}")


if __name__ == "__main__":
    main()
