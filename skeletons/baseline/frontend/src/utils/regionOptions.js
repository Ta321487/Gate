/** 地址簿省市区。只收常用省、市、区，详细门牌仍手填。 */
function city(name, districts) {
  return {
    value: name,
    label: name,
    children: districts.map((d) => ({ value: d, label: d })),
  }
}

function prov(name, cities) {
  return { value: name, label: name, children: cities }
}

